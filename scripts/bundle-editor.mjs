/**
 * Bundle assets/editor/entry.mjs into assets/vendor/codemirror.bundle.mjs.
 *
 * The output is committed so the runtime needs no build step and no CDN. CI re-runs
 * this script and fails on a diff, which keeps the committed bundle honest.
 */

import { build } from "esbuild";

await build({
  entryPoints: ["assets/editor/entry.mjs"],
  outfile: "assets/vendor/codemirror.bundle.mjs",
  bundle: true,
  format: "esm",
  target: ["es2022"],
  minify: true,
  legalComments: "none",
  banner: {
    js: "/* Generated by scripts/bundle-editor.mjs from assets/editor/entry.mjs. Do not edit by hand. */",
  },
  logLevel: "info",
});

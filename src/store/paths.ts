/**
 * paths.ts: canonical on-disk locations, id validation, and the traversal guard every
 * HTTP route and tool argument passes through before touching the filesystem.
 *
 * State root: ~/.chudcode/ (override with CHUDCODE_DIR; tests point it at a temp dir).
 *
 *   <root>/
 *     config.json  server.json
 *     problems/<slug>/   meta.json statement.md tests.json reference.py hints.json
 *                        generators.py? checker.py?
 *     sessions/<id>/     session.json events.jsonl draft.py submissions/NN.py NN.result.json
 *     lessons/<id>/      session.json events.jsonl draft.md answers/NN.md
 *     exercises/<slug>/  meta.json brief.md teaching.md private.json
 *     curriculum/fact-checks.jsonl
 *     review/events.jsonl
 *     trends.json
 *     tmp/<runId>/       ephemeral runner workdirs
 *
 * The id validators here are deliberately strict: a slug or session id is the only
 * thing standing between a URL segment or a model-supplied argument and a path.
 * The guard shape follows pi-teach's src/paths.ts (Josh Noll, MIT); see
 * docs/ATTRIBUTION.md.
 */

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

let baseDir: string = process.env["CHUDCODE_DIR"] ?? path.join(os.homedir(), ".chudcode");

/** Root directory holding all learner state. */
export function rootDir(): string {
  return baseDir;
}

/** Point the whole tool at another root. Intended for tests and dev scripts. */
export function _overrideRootDir(dir: string): void {
  baseDir = dir;
}

// ── Ids ───────────────────────────────────────────────────────────────────────

/** Problem slugs and pattern ids: lowercase kebab-case, at most 64 characters. */
export const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const MAX_SLUG_LENGTH = 64;

export function isValidSlug(value: unknown): value is string {
  return (
    typeof value === "string" &&
    value.length > 0 &&
    value.length <= MAX_SLUG_LENGTH &&
    SLUG_RE.test(value)
  );
}

/** Session ids: `YYYYMMDD-HHMM-<slug>-<4 hex>`, generated by the sessions store. */
export const SESSION_ID_RE = /^\d{8}-\d{4}-[a-z0-9]+(?:-[a-z0-9]+)*-[0-9a-f]{4}$/;

export function isValidSessionId(value: unknown): value is string {
  return (
    typeof value === "string" && value.length <= MAX_SLUG_LENGTH + 20 && SESSION_ID_RE.test(value)
  );
}

/** Turn arbitrary text into a usable slug, or `fallback` when nothing survives. */
export function slugify(input: string, fallback = "problem"): string {
  const slug = input
    .toLowerCase()
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, MAX_SLUG_LENGTH)
    .replace(/-+$/g, "");
  return slug || fallback;
}

// ── State directories ─────────────────────────────────────────────────────────

export function configFile(): string {
  return path.join(baseDir, "config.json");
}

export function serverFile(): string {
  return path.join(baseDir, "server.json");
}

export function problemsDir(): string {
  return path.join(baseDir, "problems");
}

export function problemDir(slug: string): string {
  assertSlug(slug);
  return path.join(problemsDir(), slug);
}

export function sessionsDir(): string {
  return path.join(baseDir, "sessions");
}

export function sessionDir(id: string): string {
  if (!isValidSessionId(id)) throw new Error(`Invalid session id: ${JSON.stringify(id)}`);
  return path.join(sessionsDir(), id);
}

export function lessonsDir(): string {
  return path.join(baseDir, "lessons");
}

/** Lesson sessions share the session id format, so one validator guards both. */
export function lessonDir(id: string): string {
  if (!isValidSessionId(id)) throw new Error(`Invalid lesson session id: ${JSON.stringify(id)}`);
  return path.join(lessonsDir(), id);
}

export function exercisesDir(): string {
  return path.join(baseDir, "exercises");
}

export function exerciseDir(slug: string): string {
  assertSlug(slug);
  return path.join(exercisesDir(), slug);
}

export function factChecksFile(): string {
  return path.join(baseDir, "curriculum", "fact-checks.jsonl");
}

export function reviewEventsFile(): string {
  return path.join(baseDir, "review", "events.jsonl");
}

export function trendsFile(): string {
  return path.join(baseDir, "trends.json");
}

export function tmpDir(): string {
  return path.join(baseDir, "tmp");
}

function assertSlug(slug: string): void {
  if (!isValidSlug(slug)) throw new Error(`Invalid slug: ${JSON.stringify(slug)}`);
}


// ── Traversal guard ───────────────────────────────────────────────────────────

/**
 * Resolve `relative` beneath `root`, or return null when the result escapes it.
 *
 * Checking the resolved path, rather than searching the string for "..", also rejects
 * absolute paths and encoded separators in one place.
 */
export function safeJoin(root: string, relative: string): string | null {
  if (relative.includes("\0")) return null;
  const resolvedRoot = path.resolve(root);
  const target = path.resolve(resolvedRoot, relative);
  if (target !== resolvedRoot && !target.startsWith(resolvedRoot + path.sep)) return null;
  return target;
}

export function isDir(p: string): boolean {
  try {
    return fs.statSync(p).isDirectory();
  } catch (err) {
    if (isMissing(err)) return false;
    throw err;
  }
}

export function isFile(p: string): boolean {
  try {
    return fs.statSync(p).isFile();
  } catch (err) {
    if (isMissing(err)) return false;
    throw err;
  }
}

export function isMissing(err: unknown): boolean {
  const code = (err as NodeJS.ErrnoException).code;
  return code === "ENOENT" || code === "ENOTDIR";
}
